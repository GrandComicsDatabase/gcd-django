def markdown(text):
    text = ' '.join(text.split())
    for character in '\\`*_[]<>':
        text = text.replace(character, '\\' + character)
    return text


class WikiGuide:
    """Record browser actions as Markdown instructions and screenshots."""

    def __init__(self, page, base_url):
        self.page = page
        self.base_url = base_url
        self.images = {}
        self.lines = [
            '<style>',
            ':root {',
            '  --md-primary-fg-color: #6666ee;',
            '  --md-primary-fg-color--light: #b3cff8;',
            '  --md-primary-fg-color--dark: #444444;',
            '  --md-accent-fg-color: #a9302a;',
            '  --md-typeset-a-color: #0000ee;',
            '}',
            '</style>', '',
            '# GCD user guide', '',
            'These instructions and screenshots are generated together from '
            'tested browser actions and the current interface labels.', '',
        ]
        self.steps = []

    def document(self, filename, title):
        self.current_title = title
        self.lines.extend([f'## {title}', ''])
        self.steps = []

    def open(self, path):
        response = self.page.goto(self.base_url + path)
        assert response.status == 200
        self.steps.append(f'Open **{markdown(self.page.title())}** '
                          f'(`{path}`).')

    @staticmethod
    def label(locator, fallback):
        return locator.evaluate('''(element) => {
            const label = element.labels && element.labels[0];
            return element.getAttribute('aria-label') ||
                (label && label.innerText) ||
                element.getAttribute('placeholder') ||
                element.innerText || element.value || element.name || '';
        }''').strip() or fallback

    def select(self, locator, value):
        locator.select_option(value)
        option = locator.locator('option:checked').inner_text()
        self.steps.append(
            f'Select **{markdown(option)}** in the search selector.')

    def fill(self, locator, value):
        label = self.label(locator, 'field')
        locator.fill(value)
        if locator.get_attribute('type') == 'password':
            self.steps.append(f'Enter your password in **{markdown(label)}**.')
        else:
            self.steps.append(f'Enter **{markdown(value)}** '
                              f'in **{markdown(label)}**.')

    def click(self, locator, fallback='button'):
        label = self.label(locator, fallback)
        locator.click()
        self.steps.append(f'Select **{markdown(label)}**.')

    def capture(self, name, fields=False):
        self.page.wait_for_load_state('load')
        self.page.evaluate('document.fonts.ready')
        assert self.page.evaluate('document.styleSheets.length') > 0
        title = markdown(self.page.title().strip() or
                         self.current_title)
        self.lines.extend([f'### {title}', ''])
        self.lines.extend(f'{number}. {step}' for number, step in
                          enumerate(self.steps, start=1))
        self.lines.extend(['', f'![{title}](images/{name}.png)', ''])
        if fields:
            labels = self.page.locator(
                'form label:visible').all_text_contents()
            labels = list(dict.fromkeys(markdown(label) for label in labels
                                        if label.strip()))
            if labels:
                self.lines.extend(['Fields shown on this page:', ''])
                self.lines.extend(f'- {label}' for label in labels)
                self.lines.append('')
        self.images[name] = self.page.screenshot(
            full_page=True, animations='disabled', caret='hide')
        self.steps = []

    def write(self):
        root = Path(__file__).resolve().parents[2] / 'docs/wiki'
        (root / 'images').mkdir(parents=True, exist_ok=True)
        notice = '<!-- Generated by tests/wiki. Do not edit by hand. -->\n\n'
        self.lines.extend([
            '## Coverage', '',
            'The examples use fictional records marked **[GCD DEV]** and '
            'placeholder covers; search for real names on the public site.',
            '',
            'Coverage is limited to the workflows listed above. Editing, '
            'approval, cover uploads, administration and My Comics are not '
            'yet included. Business rules cannot be inferred from page '
            'labels.', '',
        ])
        (root / 'index.md').write_text(
            notice + '\n'.join(self.lines), encoding='utf-8')
        for name, data in self.images.items():
            (root / 'images' / f'{name}.png').write_bytes(data)


