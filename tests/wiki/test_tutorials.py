@pytest.fixture
def page(wiki_catalog, live_server, browser_name, browser_type_launch_args,
         browser_context_args):
    # Start Playwright only after database setup and stop it before teardown.
    with sync_playwright() as playwright:
        browser = getattr(playwright, browser_name).launch(
            **browser_type_launch_args)
        try:
            yield browser.new_page(**browser_context_args)
        finally:
            browser.close()


def test_catalog_tutorial(wiki_catalog, live_server, page):
    origin = urlsplit(live_server.url).netloc
    failed_requests = []

    def local_requests_only(route):
        if urlsplit(route.request.url).netloc == origin:
            route.continue_()
        else:
            route.abort()

    def check_response(response):
        if (response.status >= 400 and
                response.request.resource_type in
                ('document', 'stylesheet', 'script')):
            failed_requests.append(response.url)

    page.route('**/*', local_requests_only)
    page.on('response', check_response)
    guide = WikiGuide(page, live_server.url)

    def search_for(kind, query):
        guide.open('/')
        search = page.locator('form[action="/search/"]').first
        guide.select(search.locator('select[name="search_type"]'), kind)
        guide.fill(search.locator('input[name="query"]'), query)
        guide.click(search.locator('[type="submit"]'), 'search button')

    guide.document('search', 'Search the catalog')
    guide.open('/')
    expect(page.locator('input[name="query"]')).to_be_visible()
    guide.capture('search-home')
    search_for('series', '[GCD DEV] Adventures')
    series_link = page.locator(f'a[href="{wiki_catalog["series"]}"]').first
    expect(series_link).to_be_visible()
    guide.capture('search-results')

    guide.document('catalog', 'Explore publishers, series and issues')
    search_for('series', '[GCD DEV] Adventures')
    guide.click(series_link)
    expect(page).to_have_url(live_server.url + wiki_catalog['series'])
    issue_link = page.locator(f'a[href="{wiki_catalog["issue"]}"]').first
    expect(issue_link).to_be_visible()
    guide.capture('series')
    guide.click(issue_link)
    expect(page).to_have_url(live_server.url + wiki_catalog['issue'])
    expect(page.locator('body')).to_contain_text('[GCD DEV] Adventures')
    guide.capture('issue')

    for kind, path, title in wiki_catalog['sections']:
        if kind == 'creator':
            guide.document('people-and-characters',
                           'Find creators, characters, groups and features')
        search_for(kind, title)
        link = page.locator(f'a[href="{path}"]').first
        expect(link).to_be_visible()
        guide.click(link)
        expect(page).to_have_url(live_server.url + path)
        expect(page.locator('body')).to_contain_text(title)
        guide.capture(kind)

    guide.document('advanced-search', 'Use advanced queries')
    guide.open('/')
    guide.click(page.locator('a[href="/search/advanced/"]:visible').first)
    expect(page.locator('#advanced_search_form')).to_be_visible()
    guide.capture('advanced-search', fields=True)

    guide.document('account', 'Open the sign-in form')
    guide.open('/')
    guide.click(page.locator('button.dropdown-toggle:visible').first,
                'account menu')
    guide.click(page.locator('input[name="login"]:visible').first)
    expect(page.locator('input[name="username"]')).to_be_visible()
    expect(page.locator('input[name="password"]')).to_be_visible()
    guide.capture('login', fields=True)

    assert not failed_requests, failed_requests
    guide.write()
